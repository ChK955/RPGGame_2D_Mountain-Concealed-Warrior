async (page,{startLevelOne}) => {
  const checks=[], errors=[], failedRequests=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('response',r=>{if(r.status()>=400)failedRequests.push(`${r.status()} ${r.url()}`);});
  const check=(name,pass,detail)=>{checks.push({name,pass,detail});if(!pass)throw new Error(name+': '+JSON.stringify(detail));};
  const inspect=()=>page.evaluate(()=>window.__MISTBOUND__.inspect());
  await page.goto('http://localhost:5177/');
  await startLevelOne(page);
  await page.locator('#game-container').click({position:{x:300,y:300}});
  let s=await inspect();check('boot / health / 12 enemies',s.hp===120&&s.enemies.length===12,s.hp);
  const x0=s.player.x;
  await page.keyboard.down('d');await page.waitForTimeout(500);await page.keyboard.up('d');
  s=await inspect();check('D moves right',s.player.x>x0+80,s.player.x);
  await page.keyboard.down('a');await page.waitForTimeout(320);await page.keyboard.up('a');
  s=await inspect();check('A turns left',s.player.facing===-1,s.player);
  await page.waitForTimeout(200);
  await page.keyboard.press('Space');await page.waitForTimeout(100);
  const jump1=await inspect();
  check('jump lifts from ground',jump1.player.y<530&&jump1.state==='Jump',jump1.player);
  await page.keyboard.press('Space');await page.waitForTimeout(100);
  const jump2=await inspect();check('no infinite air jump',jump2.player.vy>jump1.player.vy,jump2.player);
  await page.waitForFunction(()=>window.__MISTBOUND__.inspect().player.grounded);
  await page.keyboard.press('j');await page.waitForTimeout(60);
  s=await inspect();check('attack animation has state priority',s.state==='Attack'&&s.player.animation==='player-attack',s.state);
  await page.keyboard.down('d');await page.waitForTimeout(80);await page.keyboard.up('d');
  s=await inspect();check('movement does not replace attack animation',s.player.animation==='player-attack',s.player.animation);
  await page.waitForTimeout(400);await page.keyboard.press('k');
  await page.waitForFunction(()=>window.__MISTBOUND__.inspect().attacks.some(a=>a.projectile&&a.active),null,{timeout:2500});
  s=await inspect();check('skill creates an independent projectile',s.attacks.some(a=>a.projectile&&a.active)&&s.skillCooldown>3000,s.attacks);
  const cooldown=s.skillCooldown;
  await page.keyboard.press('k');await page.waitForTimeout(120);
  s=await inspect();check('skill cooldown blocks rapid reuse',s.skillCooldown<cooldown&&s.skillCooldown>0,s.skillCooldown);
  await page.waitForTimeout(350);const dashX=(await inspect()).player.x;
  await page.keyboard.press('Shift');await page.waitForTimeout(120);s=await inspect();
  check('dash moves quickly with independent state',s.state==='Dash'&&Math.abs(s.player.x-dashX)>65,s.player);
  await page.waitForFunction(()=>window.__MISTBOUND__.inspect().state!=='Dash');
  await page.keyboard.press('Shift');await page.waitForTimeout(50);s=await inspect();
  check('dash cooldown prevents consecutive dash',s.dashCooldown>0&&s.state!=='Dash',s.state);
  await page.keyboard.press('q');s=await inspect();check('full health does not consume potion',s.potionCount===3,s.potionCount);
  await page.keyboard.press('Escape');await page.waitForTimeout(80);
  const frozen=await page.evaluate(()=>{const s=window.__MISTBOUND__.getSession();return {now:s.now,x:s.enemies[0].x,frame:s.enemies[0].sprite.frame.name};});
  await page.keyboard.press('j');await page.waitForTimeout(400);
  const still=await page.evaluate(()=>{const s=window.__MISTBOUND__.getSession();return {now:s.now,x:s.enemies[0].x,frame:s.enemies[0].sprite.frame.name};});
  check('pause freezes AI, simulation and animation',JSON.stringify(frozen)===JSON.stringify(still),{frozen,still});
  await page.screenshot({path:'output/playwright/02-paused.png'});
  await page.getByRole('button',{name:'招式与身法'}).click();
  check('controls menu opens',await page.locator('#controls-list').isVisible(),true);
  await page.getByRole('button',{name:'继续旅程'}).click();await page.waitForTimeout(80);
  check('resume returns keyboard focus to game',(await inspect()).paused===false,await page.evaluate(()=>document.activeElement?.id));
  await page.keyboard.press('F1');await page.waitForTimeout(60);
  check('F1 toggles debug', (await inspect()).debug===true,true);
  await page.screenshot({path:'output/playwright/03-debug.png'});
  await page.keyboard.press('F1');
  for(let i=0;i<3;i++){
    await page.keyboard.press('Escape');await page.getByRole('button',{name:'重新启程'}).click();
    await page.waitForTimeout(180);
    check(`restart ${i+1} restores a healthy run`,(await inspect()).hp===120&&(await inspect()).kills===0,true);
  }
  check('no runtime errors or missing requests',errors.length===0&&failedRequests.length===0,{errors,failedRequests});
  return {checks,errors,failedRequests};
}
